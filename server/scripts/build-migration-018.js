// Generate migrations/018_relaunch_hide_mislabelled_pd.sql from
// data/pd78s-1926-identifiers.txt, so the migration needs no network or files
// at run time. Re-run only if the list is rebuilt:
//   node scripts/build-migration-018.js > migrations/018_relaunch_hide_mislabelled_pd.sql
import fs from 'node:fs';

const ids = fs.readFileSync(new URL('../data/pd78s-1926-identifiers.txt', import.meta.url), 'utf8')
  .split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "''");
const values = ids.map((id) => `('${esc(id)}')`);
const chunks = [];
for (let i = 0; i < values.length; i += 500) chunks.push(values.slice(i, i + 500).join(',\n  '));

process.stdout.write(`-- Relaunch G3 (2026-10-25): hide tracks wrongly labelled public domain
-- (relaunch item 6, owner decision 3). Reversible: rows are hidden, never
-- deleted; hidden_at/hidden_reason say why. One field changes: Jukebox rows'
-- license goes from 'public-domain' to 'loc-jukebox-stream-only' (every one
-- of them was 'public-domain', so that is reversible too). Generated by
-- scripts/build-migration-018.js from data/pd78s-1926-identifiers.txt.
--
-- Production counts on 2026-10-25 (read-only): National Jukebox 9,200,
-- American Folklife Center 1,146, Musopen "European Archive" 2,179,
-- rows from 1926 items 2,578 (archive_pd78s 2,558 + archive_subjects 20).
-- Each step first checks a ceiling and aborts the whole migration (error 3141, nothing committed)
-- if a predicate matches far more rows than expected. Each step prints how
-- many rows it is about to hide, so the run log records the counts.

START TRANSACTION;

-- 1. Library of Congress National Jukebox: streaming on loc.gov only, rights
--    reserved (Sony license to LoC). Relabelled so nothing calls them PD.
SELECT COUNT(*) INTO @n FROM tracks WHERE source = 'loc_jukebox' AND external_id LIKE 'jukebox-%' AND hidden_at IS NULL;
SELECT 'national jukebox' AS step, @n AS rows_to_hide;
SET @guard = IF(@n > 9500, JSON_EXTRACT('ceiling exceeded: loc jukebox', '$'), 0);
UPDATE tracks
   SET hidden_at = NOW(), hidden_reason = 'rights_loc_jukebox',
       hidden_note = 'National Jukebox: streaming on loc.gov only; was labelled public-domain',
       license = 'loc-jukebox-stream-only'
 WHERE source = 'loc_jukebox' AND external_id LIKE 'jukebox-%' AND hidden_at IS NULL;

-- 2. LoC American Folklife Center items: hidden until scripts/check-loc-rights.js
--    has checked each item's rights statement (owner decision 3).
SELECT COUNT(*) INTO @n FROM tracks WHERE source = 'loc_jukebox' AND external_id NOT LIKE 'jukebox-%' AND hidden_at IS NULL;
SELECT 'american folklife center' AS step, @n AS rows_to_hide;
SET @guard = IF(@n > 1300, JSON_EXTRACT('ceiling exceeded: loc afc', '$'), 0);
UPDATE tracks
   SET hidden_at = NOW(), hidden_reason = 'rights_check_pending',
       hidden_note = 'American Folklife Center item; LoC rights statement not yet checked'
 WHERE source = 'loc_jukebox' AND external_id NOT LIKE 'jukebox-%' AND hidden_at IS NULL;

-- 3. Musopen "European Archive" LP transfers (1950s-60s; EU 50-year PD, not US PD).
SELECT COUNT(*) INTO @n FROM tracks WHERE source = 'musopen' AND license = 'public-domain' AND artist_name LIKE '%European Archive%' AND hidden_at IS NULL;
SELECT 'musopen european archive' AS step, @n AS rows_to_hide;
SET @guard = IF(@n > 2500, JSON_EXTRACT('ceiling exceeded: musopen european archive', '$'), 0);
UPDATE tracks
   SET hidden_at = NOW(), hidden_reason = 'rights_musopen_european_archive',
       hidden_note = 'European Archive LP transfer; not public domain in the US'
 WHERE source = 'musopen' AND license = 'public-domain' AND artist_name LIKE '%European Archive%' AND hidden_at IS NULL;

-- 4. Rows from Internet Archive items dated 1926: protected in the US until
--    2027-01-01. archive_pd78s (the query bug) and archive_subjects (20 rows
--    whose uploaders labelled them CC BY-SA; owner decision, follow-up 4).
--    scripts/unhide-pd-effective.js unhides them then.
-- Same collation as tracks.external_id, whatever the database default is (review R1).
CREATE TEMPORARY TABLE pd1926 (identifier VARCHAR(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL PRIMARY KEY) ENGINE=InnoDB;
${chunks.map((c) => `INSERT INTO pd1926 (identifier) VALUES\n  ${c};`).join('\n')}
SELECT COUNT(*) INTO @n FROM tracks t JOIN pd1926 p ON p.identifier = SUBSTRING_INDEX(t.external_id, ':', 1)
 WHERE t.source IN ('archive_pd78s', 'archive_subjects') AND t.hidden_at IS NULL;
SELECT '1926 recordings' AS step, @n AS rows_to_hide;
SET @guard = IF(@n > 3000, JSON_EXTRACT('ceiling exceeded: pd78s 1926', '$'), 0);
UPDATE tracks t JOIN pd1926 p ON p.identifier = SUBSTRING_INDEX(t.external_id, ':', 1)
   SET t.hidden_at = NOW(), t.hidden_reason = 'pd_not_yet_1926', t.pd_effective_on = '2027-01-01',
       t.hidden_note = 'Recorded 1926: US public domain on 2027-01-01 (17 USC 1401)'
 WHERE t.source IN ('archive_pd78s', 'archive_subjects') AND t.hidden_at IS NULL;
DROP TEMPORARY TABLE pd1926;

COMMIT;
`);
